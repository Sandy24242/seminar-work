"""
Inventory the real datasets on (mounted) Google Drive and write docs-ready JSON + Markdown.

    python ml/inventory_datasets.py --out inventory                      # uses DCAI_DATA_ROOT (default MyDrive/dentalcaries)
    python ml/inventory_datasets.py --root /content/drive/MyDrive/dentalcaries --dup-hamming 2 --check-zips

Reports per dataset: image counts, folder structure, class labels and their source, annotation format problems,
corrupt images, duplicates, per-view counts (views are NOT labels) and whether patient identifiers exist.
"""
import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from dcai_data.paths import DATASETS, DataPaths  # noqa: E402
from dcai_data.validate import (find_duplicates, inventory_class_folders, inventory_yolo, list_images, view_of,  # noqa: E402
                                zip_integrity)


def folder_tree(root, depth=3):
    lines = []
    for dp, dn, fn in os.walk(root):
        level = os.path.relpath(dp, root).count(os.sep) if dp != root else 0
        if level >= depth:
            dn[:] = []
            continue
        n_img = sum(f.lower().endswith((".jpg", ".jpeg", ".png")) for f in fn)
        lines.append(f"{'  ' * level}{os.path.basename(dp) or dp}/  ({n_img} images, {len(fn)} files)")
        dn.sort()
    return lines


def patient_id_report(paths):
    """No dataset documents patient IDs. We only report whether filenames share a recognisable prefix (heuristic)."""
    stems = [os.path.splitext(os.path.basename(p))[0] for p in paths]
    prefixes = {s.split("_")[0].split("-")[0] for s in stems}
    return {"documented_patient_ids": False,
            "distinct_filename_prefixes": len(prefixes),
            "note": "No patient-ID field or manifest was found; splits must be grouped by near-duplicate image hashing "
                    "(as the training notebook does), not by patient."}


def run(root, dup_hamming, check_zips):
    P = DataPaths(root) if root else DataPaths()
    report = {"paths": P.describe(), "datasets": {}}
    for key in DATASETS:
        d = P.dataset_dir(key)
        entry = {"dir": d}
        if check_zips and os.path.isfile(P.dataset_zip(key)):
            ok, n, bad = zip_integrity(P.dataset_zip(key))
            entry["zip"] = {"ok": ok, "members": n, "first_bad_member": bad}
        if not os.path.isdir(d):
            entry["status"] = "folder not found"
            report["datasets"][key] = entry
            continue
        imgs = list_images(d)
        entry.update(n_images=len(imgs), tree=folder_tree(d),
                     images_per_view={v: sum(view_of(os.path.relpath(p, d)) == v for p in imgs)
                                      for v in sorted({view_of(os.path.relpath(p, d)) or "unknown" for p in imgs})},
                     patient_ids=patient_id_report(imgs))
        if key == "fdi":
            sub = next((os.path.join(d, s) for s in os.listdir(d) if os.path.isdir(os.path.join(d, s, "images"))), d)
            entry["annotations"] = inventory_yolo(sub, exclude_dirs=("only fdi",))
            entry["task_support"] = "FDI tooth detection (YOLO boxes, class = FDI number)"
        elif key == "icdas":
            entry["annotations"] = inventory_class_folders(d)
            entry["task_support"] = "ICDAS 1-6 classification of crops (folder name = score); ICDAS 0 absent"
        elif key in ("caries_views", "lower_occlusal_yolo"):
            entry["annotations"] = inventory_yolo(d)
            entry["task_support"] = ("lesion localization / G.V. Black only if YOLO labels exist AND the class-ID mapping "
                                     "is documented; view folders are not labels")
        elif key == "healthy":
            entry["task_support"] = "negative (healthy) class for Stage 1 healthy-vs-caries"
        if dup_hamming is not None:
            groups = find_duplicates(imgs, dup_hamming)
            entry["duplicates"] = {"max_hamming": dup_hamming, "n_groups": len(groups),
                                   "n_images_in_groups": sum(len(g) for g in groups),
                                   "examples": [[os.path.relpath(p, d) for p in g] for g in groups[:20]]}
        report["datasets"][key] = entry
    return report


def to_markdown(rep):
    out = ["# Dataset inventory (generated by ml/inventory_datasets.py)", ""]
    for k, e in rep["datasets"].items():
        out += [f"## {k}", f"- folder: `{e['dir']}`"]
        if "status" in e:
            out += [f"- **{e['status']}**", ""]
            continue
        out += [f"- images: {e['n_images']}", f"- supports: {e.get('task_support', '')}",
                f"- images per view (views are not labels): {e['images_per_view']}"]
        a = e.get("annotations", {})
        for f in ("class_names_source", "boxes_per_class", "images_per_class", "n_unlabelled", "n_label_problems",
                  "n_orphan_labels"):
            if f in a:
                out.append(f"- {f}: {a[f]}")
        out.append(f"- corrupt images: {len(a.get('corrupt_images', []))}")
        if "duplicates" in e:
            out.append(f"- duplicate groups (hamming ≤ {e['duplicates']['max_hamming']}): {e['duplicates']['n_groups']}")
        if "zip" in e:
            out.append(f"- zip integrity: {e['zip']}")
        out += ["", "```", *e["tree"][:60], "```", ""]
    return "\n".join(out)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=None, help="folder with the dataset folders (default: $DCAI_DATA_ROOT)")
    ap.add_argument("--out", default="dataset_inventory")
    ap.add_argument("--dup-hamming", type=int, default=0, help="dHash distance for duplicates; -1 to skip")
    ap.add_argument("--check-zips", action="store_true", help="CRC-check every member of each archive (slow)")
    a = ap.parse_args()
    rep = run(a.root, None if a.dup_hamming < 0 else a.dup_hamming, a.check_zips)
    with open(a.out + ".json", "w") as f:
        json.dump(rep, f, indent=2)
    with open(a.out + ".md", "w") as f:
        f.write(to_markdown(rep))
    print(f"wrote {a.out}.json and {a.out}.md")
